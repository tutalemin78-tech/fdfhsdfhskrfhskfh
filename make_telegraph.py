# -*- coding: utf-8 -*-
"""
Генератор красивого Telegraph-справочника по SendFlow.
Запусти локально (нужен интернет):  python3 make_telegraph.py
Скрипт создаст страницу и выведет ссылку — вставь её в config.HELP_URL / кнопку.
Если пакета telegraph нет:  pip install telegraph
"""
import json
import os
HTML = '\n<h3>SendFlow — обновлённый справочник</h3>\n<p>4 дня полного PRO, до 5 аккаунтов по умолчанию. Текст, одиночное фото или видео, копирование поста по ссылке, до 3 дополнительных вариантов текста. Защищённые посты и альбомы по ссылке не копируются.</p>\n<p>Каждое сообщение содержит подпись «Отправлено с помощью @SendFlowTgBot». Кнопки пользовательских аккаунтов превращаются в ссылки. Предпросмотр показывает фактических получателей; личные сообщения исключены. Тест в Избранное, пауза, продолжение и остановка.</p>\n<h3>Расписание в Mini App</h3><p>Один раз, ежедневно или по дням недели с часовым поясом. Пропущенные публикации приостанавливаются, их нужно перенести вручную.</p>\n<h3>Уведомления и автоответ</h3><p>В настройках аккаунта включаются уведомления об ответах на рассылку и новых личных сообщениях. Бот показывает цитату и кнопку перехода. В группе требуется доступ к чату; для личного сообщения открывается диалог или профиль. Автоответ в личных сообщениях — всегда либо вне рабочих часов, не чаще одного раза в 24 часа собеседнику. Для работы нужен постоянно включённый сервер и активный PRO.</p>\n<h3>Доступ и безопасность</h3><p>Пробный период даёт те же продуктовые права PRO. Telegram может ограничивать отправки — гарантии «антибана» нет. Сессия даёт доступ к аккаунту; используйте рабочий аккаунт. Удаление пытается отозвать Telegram-сессию. Если отзыв не подтверждён, завершите сеанс в Telegram → Настройки → Устройства.</p>\n<p>Актуальные лимиты и цена — в боте. /help — полный справочник, /trial — пробный период, /privacy — хранение данных, /stopall — остановка, /recipients — список, /testsend — тест. Платёж Stars подтверждается автоматически, ручная оплата — через указанный в боте контакт. Бонус за реферала начисляется один раз за нового пользователя.</p>\n'

def _create_page():
    """Создаёт страницу в Telegraph и возвращает URL (или бросает исключение)."""
    from telegraph import Telegraph
    tg = Telegraph()
    tg.create_account(short_name='SendFlow')
    res = tg.create_page(title='SendFlow — справочник', html_content=HTML, author_name='SendFlow')
    return 'https://telegra.ph/' + res['path']

def ensure_help_page(cache_path=None):
    """Возвращает URL справочника. Есть кэш — берём оттуда,
    иначе создаём страницу и кэшируем. Без интернета/пакета — None."""
    if cache_path and os.path.exists(cache_path):
        try:
            with open(cache_path, 'r', encoding='utf-8') as f:
                u = json.load(f).get('url')
                if u:
                    return u
        except Exception:
            pass
    try:
        url = _create_page()
    except Exception:
        return None
    if cache_path:
        try:
            with open(cache_path, 'w', encoding='utf-8') as f:
                json.dump({'url': url}, f)
        except Exception:
            pass
    return url

def main():
    url = ensure_help_page()
    if url:
        print('Готово! Ссылка на справочник:')
        print(url)
    else:
        print('Не удалось создать страницу. Установи пакет:  pip install telegraph')
if __name__ == '__main__':
    main()
